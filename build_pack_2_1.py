def card(id, source, group, part, title, stimulus, answers, explanation, **kw):
    q = {
        "id": id, "source": source, "group": group, "part": str(part),
        "lessonId": "2-1", "topic": "person", "kind": "fields",
        "title": title, "stimulus": stimulus,
        "fields": [{"label": kw.pop("label", "Ответ"), "kind": "text",
                    "answers": answers if isinstance(answers, list) else [answers]}],
        "explanation": explanation, "ruleIds": kw.pop("ruleIds", ["person-sg"]),
    }
    extra = kw.pop("extra_fields", None)
    if extra: q["fields"].extend(extra)
    q.update({k: v for k, v in kw.items() if v is not None})
    return q

