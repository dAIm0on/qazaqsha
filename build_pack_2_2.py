def card(id, source, group, part, topic, title, stimulus, answers, explanation, **kw):
    q = {
        "id": id,
        "source": source,
        "group": group,
        "part": str(part),
        "lessonId": "2-2",
        "topic": topic,
        "kind": "fields",
        "title": title,
        "stimulus": stimulus,
        "fields": [{"label": kw.pop("label", "Ответ"), "kind": "text", "answers": answers if isinstance(answers, list) else [answers]}],
        "explanation": explanation,
    }
    extra_fields = kw.pop("extra_fields", None)
    if extra_fields:
        q["fields"].extend(extra_fields)
    q.update({k: v for k, v in kw.items() if v is not None})
    return q


def vocab_pair(n, kk, ru, extra_ru=None, extra_kk=None, hint=None, note=None):
    ru_ans = extra_ru or ([ru] if isinstance(ru, str) else list(ru))
    kk_ans = extra_kk or [kk]
    ru_prompt = ru if isinstance(ru, str) else ru[0]
    kk_card = card(f"hw22-{n}-kk", "hw22", "words", f"{n}-kk", "vocab", "Переведи на казахский", ru_prompt, kk_ans, f"{kk} — {ru_prompt}.", hint=hint, note=note, ruleIds=["person-vocab"])
    ru_card = card(f"hw22-{n}-ru", "hw22", "words", f"{n}-ru", "vocab", "Переведи на русский", kk, ru_ans, f"{kk} — {ru_prompt}.", hint=hint or ru_prompt, note=note, ruleIds=["person-vocab"])
    return [kk_card, ru_card]


