function card(o){
  const row={
    id:o.id,origin:o.origin||'authored',topic:o.topic||'locative',
    title:o.title,stimulus:o.stimulus,
    fields:o.fields,explanation:o.explanation||'Сверь форму по правилу урока 5–1.',
    rule_ids:o.rule_ids||['v2:5-1:summary'],source_refs:o.source_refs||[SR]
  };
  if(o.source_item)row.source_item=o.source_item;
  if(o.prompt_original)row.prompt_original=o.prompt_original;
  if(o.note)row.note=o.note;
  return row;
}
function text(id,title,stimulus,answers,rule,extra={}){
  return card({id,title,stimulus,fields:[{label:extra.label||'Ответ',kind:'text',answers:[].concat(answers)}],rule_ids:[rule||'v2:5-1:summary'],...extra});
}
function choice(id,title,stimulus,options,answers,rule,extra={}){
  return card({id,title,stimulus,fields:[{label:extra.label||'Выбери',kind:'select',options,answers:[].concat(answers)}],rule_ids:[rule||'v2:5-1:summary'],...extra});
}

